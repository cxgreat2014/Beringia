#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-only
# Darwin cross toolchain for building x86_64 XNU on a Linux host.
#
#   scripts/toolchain/setup.sh [step...]     steps: deps droidvm cctools shims appleclang makeconfig (default: all)
#
# Built on macOS-DroidVM's Linux toolchain support (pinned in scripts/lib/env.sh): its setup-env.py fetches the macOS
# SDK, the KDK headers and the reference sources; Beringia adds cctools/MIG for the x86_64-apple-darwin target, the
# Darwin tool shims configured for x86_64, AppleClang's kext runtime, and the make configuration XNU's build reads.
set -euo pipefail
. "$(dirname "$0")/../lib/env.sh"

steps=${*:-deps droidvm cctools shims appleclang makeconfig}
tc=$BERINGIA_TOOLCHAIN
dv=$BERINGIA_DROIDVM
mkdir -p "$tc/logs"

step_deps() {
	log "host packages"
	local pkgs="git make cmake ninja-build clang-21 llvm-21 lld-21 python3 python3-pip autoconf automake libtool \
		bison flex m4 tcsh pax unifdef uuid-dev libbsd-dev libmd-dev libssl-dev xz-utils cpio"
	if command -v apt-get >/dev/null; then
		echo "sudo apt-get install -y $pkgs"
		[ "${BERINGIA_INSTALL:-0}" = 1 ] && sudo apt-get install -y $pkgs
	fi
	[ -x "$LLVM_BIN/clang" ] || die "LLVM 21 not found at $LLVM_BIN"
}

step_droidvm() {
	log "macOS-DroidVM at $DROIDVM_COMMIT"
	if [ ! -d "$dv/.git" ]; then
		mkdir -p "$(dirname "$dv")"
		git clone -q "$DROIDVM_GIT" "$dv"
	fi
	git -C "$dv" checkout -q "$DROIDVM_COMMIT"
	# SDK, reference sources (libdispatch, libplatform, AvailabilityVersions), Linux tool sources (cctools-port, MIG)
	(cd "$dv" && python3 scripts/setup-env.py sdks && python3 compat/xnu-linux/scripts/setup-linux.py fetch \
		--sources toolchains/linux-sources) > "$tc/logs/droidvm.log" 2>&1 || die "DroidVM setup failed ($tc/logs/droidvm.log)"
	[ -d "$BERINGIA_SDK" ] || die "no SDK at $BERINGIA_SDK"
}

step_cctools() {
	log "cctools + MIG for x86_64-apple-darwin"
	local src=$dv/toolchains/linux-sources
	[ -d "$tc/mig-work" ] || git clone -q --no-hardlinks "$src/bootstrap_cmds-linux" "$tc/mig-work"
	if [ ! -f "$tc/mig-work/Makefile" ]; then
		(cd "$tc/mig-work" && autoreconf --install && ./configure --prefix="$tc/toolchain") > "$tc/logs/mig-configure.log" 2>&1
	fi
	make -C "$tc/mig-work" -j"$BERINGIA_JOBS" install > "$tc/logs/mig.log" 2>&1
	[ -d "$tc/cctools-work" ] || git clone -q --no-hardlinks "$src/cctools-port-linux" "$tc/cctools-work"
	if [ ! -f "$tc/cctools-work/cctools/Makefile" ]; then
		(cd "$tc/cctools-work/cctools" && ./configure --prefix="$tc/toolchain" --target=x86_64-apple-darwin \
			--disable-tapi-support --with-llvm-config="$LLVM_BIN/llvm-config" CC="$LLVM_BIN/clang" CXX="$LLVM_BIN/clang++") \
			> "$tc/logs/cctools-configure.log" 2>&1
	fi
	make -C "$tc/cctools-work/cctools" -j"$BERINGIA_JOBS" install > "$tc/logs/cctools.log" 2>&1
	[ -x "$tc/toolchain/bin/x86_64-apple-darwin-ld" ] || die "cctools build failed"
}

step_shims() {
	log "Darwin tool shims (target-clang, xcrun, plutil, ...) for x86_64"
	python3 -I "$BERINGIA_ROOT/scripts/toolchain/make-shims.py" "$tc" "$dv" "$BERINGIA_SDK" "$LLVM_BIN"
}

step_appleclang() {
	log "AppleClang kext runtime (libclang_rt.cc_kext.a)"
	mkdir -p "$dv/toolchains/linux/appleclang"
	python3 "$dv/compat/xnu-linux/scripts/setup-appleclang.py" fetch --directory "$dv/toolchains/linux/appleclang"
	python3 "$dv/compat/xnu-linux/scripts/setup-appleclang.py" extract --directory "$dv/toolchains/linux/appleclang"
}

step_makeconfig() {
	log "XNU make configuration ($BERINGIA_XNU_MK)"
	local ccw=$tc/cctools-work/cctools
	local rt
	rt=$(ls "$dv"/toolchains/linux/appleclang/apple-tools/Library/Developer/CommandLineTools/usr/lib/clang/*/lib/darwin/libclang_rt.cc_kext.a 2>/dev/null | head -1)
	[ -n "$rt" ] || die "no libclang_rt.cc_kext.a (step appleclang)"
	cat > "$BERINGIA_XNU_MK" <<EOF
# Generated by scripts/toolchain/setup.sh: host/target tool selection for XNU's build on Linux.
override XCRUN := $tc/binx86/xcrun
override SDKROOT_RESOLVED := $BERINGIA_SDK
override HOST_SDKROOT_RESOLVED := /
override SDKVERSION := 26.1
override PLATFORM := MacOSX
override HOST_PLATFORM := Linux
override HOST_OS_VERSION :=
override HOST_CC := $LLVM_BIN/clang
override HOST_FLEX := /usr/bin/flex
override HOST_BISON := /usr/bin/bison
override HOST_GM4 := /usr/bin/m4
override CC := $tc/binx86/target-clang
override CXX := $tc/binx86/target-clang++
override PLUTIL := $tc/binx86/plutil
override PAX := /usr/bin/pax
override LINUX_HOST_CFLAGS := -I$dv/compat/xnu-linux/linux -I$ccw/include -idirafter $ccw/include/foreign -include bsd/stdlib.h -include bsd/unistd.h -D__private_extern__=extern
override LINUX_HOST_LIBS := $ccw/libmacho/.libs/libmacho.a $ccw/libstuff/.libs/libstuff.a /usr/lib/x86_64-linux-gnu/libbsd.a /usr/lib/x86_64-linux-gnu/libmd.a -luuid
override MEMORY_SIZE := $(( $(getconf _PHYS_PAGES) * $(getconf PAGE_SIZE) ))
override SYSCTL_HW_PHYSICALCPU := $(nproc)
override SYSCTL_HW_LOGICALCPU := $(nproc)
override DO_CTFMERGE := 0
override IIG := $tc/binx86/target-iig
override SCAN_BUILD :=
override CTFINSERT :=
override CTFCONVERT :=
override CTFMERGE :=
override CTFDUMP :=
override DOCC :=
override HOST_CODESIGN_ALLOCATE :=
override LD_KERNEL_LIBS := $rt
override MIG := $tc/toolchain/bin/mig
override MIGCOM := $tc/toolchain/bin/migcom
override STRIP := $tc/toolchain/bin/x86_64-apple-darwin-strip
override LIPO := $tc/toolchain/bin/x86_64-apple-darwin-lipo
override LIBTOOL := $tc/toolchain/bin/x86_64-apple-darwin-libtool
override OTOOL := $tc/toolchain/bin/x86_64-apple-darwin-otool
override NM := $tc/toolchain/bin/x86_64-apple-darwin-nm
override UNIFDEF := /usr/bin/unifdef
override DSYMUTIL := $LLVM_BIN/dsymutil
override NMEDIT := $tc/toolchain/bin/x86_64-apple-darwin-nmedit
override GIT := /usr/bin/git
override PYTHON := /usr/bin/python3
EOF
}

for s in $steps; do
	"step_$s"
done
log "toolchain ready: $tc"
